# pipeline/web_intent.py
"""识别用户「显式要求联网检索」的指令意图。

════════════════════════════════════════════════════════════════════════
为什么需要它
════════════════════════════════════════════════════════════════════════
L4（联网）的自动触发有两道判据（见 `rag/retriever.py` 的 need_web）：

    low_conf     : 校准聚合置信度 < 0.55
    insufficient : query 实词覆盖率 < 0.6

两者都是**启发式**，必然存在漏判。实测 case：

    用户问   : 「法国最低饮酒年龄」
    离线召回 : L3_history:5, L2_wiki:8 → 聚合置信度 0.98
    实词覆盖 : "法国"/"最低"/"饮酒"/"年龄" 在维基「合法飲酒年齡」
               条目里全都出现 → 覆盖率达标
    → 两道判据都判 False → L4 不触发
    → 但那篇条目**只讲欧洲通例、没点名法国** → 模型只能拒答

这是启发式的固有盲区：证据"主题高度相关且词都齐"，却**恰好缺了
用户要的那一个具体事实**。任何基于相似度或词面覆盖的指标都无法
识别这种情况 —— 要判断"这段文字里有没有法国的那个数字"，本质上
需要阅读理解。

════════════════════════════════════════════════════════════════════════
所以给用户一个**逃生舱**
════════════════════════════════════════════════════════════════════════
与其无止境地调阈值（每次调都会在别处引入新的误判），不如承认启发式
有上限，让用户能用一句自然语言直接接管这个决策：

    「请联网搜索一下」「重新搜一下最新资料」「查一下网上怎么说」

这是 Perplexity / ChatGPT 的通行做法（Search 开关 / "search the web"），
本质是把**最终裁量权交还用户**，而不是假装启发式总是对的。

════════════════════════════════════════════════════════════════════════
为什么用规则而不是 LLM
════════════════════════════════════════════════════════════════════════
① 这是**每条 query 都要过**的前置判断，多一次 LLM 调用就是每轮多
   1~2 秒（实测 router 稳态 2.4s），代价与收益完全不成比例；
② 这个意图的表达方式**高度模式化**（动词 + 渠道词），规则足以覆盖；
③ 规则是确定性的 —— 用户说了"联网搜索"就必定联网，不会被采样波动
   影响。可预测性在"用户显式指令"这个场景里比召回率更重要：
   一个偶尔不生效的开关比没有开关更让人困惑。

════════════════════════════════════════════════════════════════════════
误判防护：为什么要求「动作 + 渠道」双信号
════════════════════════════════════════════════════════════════════════
只匹配渠道词（"网上"/"联网"）会把这些**正常提问**误判成指令：

    「网上购物的发展史」            ← 谈论网络，不是要求联网
    「如何联网打印机」              ← 问的是操作方法
    「百度和谷歌的搜索算法差异」    ← 讨论搜索引擎本身

只匹配动作词（"搜索"/"查"）同样会误伤：

    「查尔斯·达尔文的生平」        ← "查"只是姓名的一部分
    「搜索引擎的排序原理」          ← 讨论技术概念

因此要求**两类信号同时出现**。此外对"疑问句式"额外做一次排除：
以「如何/怎么/为什么/什么是」开头且以「？」结尾的，通常是在**询问
关于搜索的知识**，而不是**命令系统去搜索**。

已知局限（有意不处理）
    * 「帮我查一下」这类**不含渠道词**的省略表达不会触发。
      因为它与"查询本地资料"无法区分，强行覆盖会把大量普通
      提问误判为强制联网，代价是每次多花 2~16 秒联网。
      宁可漏判（用户可以补一句"联网"），不可误判。
    * 反向指令（「不要联网」）未实现 —— 当前默认就是离线优先，
      需要时再加。
"""
from __future__ import annotations

import re

# ── 渠道词：明确指向"外部网络"这个信息源 ──────────────────────────
# 注意不含"搜索"二字——它是动作，不是渠道（"搜索引擎"另作讨论）。
_CHANNEL = (
    "联网", "连网", "网上", "网络", "互联网", "线上", "在线",
    "网页", "web", "internet", "online",
    "外部", "实时", "最新资料", "最新消息", "最新信息",
    # 具体搜索渠道：用户点名某个引擎时，意图是毫无疑义的
    "谷歌", "google", "必应", "bing", "百度", "duckduckgo", "tavily",
)

# ── 动作词：表达"去执行检索"这个诉求 ──────────────────────────────
_ACTION = (
    "搜索", "搜一下", "搜下", "搜搜", "search",
    "检索", "查询", "查一下", "查下", "查查", "查阅", "查找",
    "找一下", "找找", "触发", "调用", "重新搜", "再搜", "搜集", "收集",
)

# ── 强指令词：单独出现即可判定（无需渠道词配合）────────────────────
# 这些短语在中文里**只**用于"命令系统去联网"，不存在其他语义。
# 例：「请联网搜索」「走一下 web 搜索」「用网络搜索」
_STRONG = (
    "联网搜索", "联网检索", "联网查", "网络搜索", "网络检索",
    "网页搜索", "网页检索", "web搜索", "web检索", "websearch",
    "在线搜索", "在线检索", "上网搜", "上网查",
    "搜索网页", "检索网页", "搜索一下网", "搜网上", "查网上",
    "search the web", "web search", "search online",
)

# ── 疑问句排除：在**问**关于搜索的知识，而非**命令**去搜索 ─────────
_INTERROGATIVE_HEAD = (
    "如何", "怎么", "怎样", "为什么", "为何", "什么是", "何谓",
    "是什么", "有什么", "哪些", "能否介绍", "介绍一下",
    "what is", "how to", "how do", "why",
)


def _normalize(text: str) -> str:
    """小写 + 去掉空白与常见标点，让「web 搜索」「web-搜索」都能匹配。

    只去分隔符不去汉字，避免把「网 上」这类误连成新词的风险很低，
    而收益是能容忍用户的各种空格/标点习惯。
    """
    t = (text or "").lower()
    return re.sub(r"[\s\-_、,，.。!！?？:：;；'\"“”‘’()（）\[\]【】]+", "", t)


def _looks_interrogative(raw: str) -> bool:
    """判断是否为「询问搜索相关知识」的疑问句（→ 不应触发强制联网）。

    条件是**开头是疑问词** —— 只看开头而不看是否含问号，因为中文
    用户常省略问号（"如何联网打印机" 同样是提问）。
    """
    t = (raw or "").strip().lower()
    return any(t.startswith(h) for h in _INTERROGATIVE_HEAD)


def wants_web_search(user_query: str) -> bool:
    """用户是否**显式要求**联网检索。

    判定顺序（短路）：
        ① 疑问句开头（如"什么是…"）→ False
           理由：这是在**问关于搜索的知识**，不是命令去搜索。
           它必须排在强指令判定**之前**：实测「什么是网络搜索」含有
           强指令词"网络搜索"，若先判强指令就会被误当成联网要求。
           代价是「能不能联网搜索一下？」这类委婉请求也会被排除，
           但那些开头词（能否/能不能）未列入 _INTERROGATIVE_HEAD，
           而"什么是/如何/为什么"开头的句子几乎不可能是指令。
        ② 命中强指令短语（如"联网搜索"）→ True
        ③ 渠道词 AND 动作词 同时出现 → True
        ④ 其余 → False

    Args:
        user_query: **用户原始输入**（不要传改写后的 query ——
                    改写器会重写措辞、丢掉"请联网搜索"这类指令性
                    表达，让手段改变意图判定即抽象泄漏。这与
                    `retriever.retrieve()` 里 route_query 用原始 query
                    的理由完全同源）。

    Returns:
        True 表示应当强制激活 L4，跳过自动判据。
    """
    if not user_query or not user_query.strip():
        return False

    norm = _normalize(user_query)

    # ① 疑问句优先排除：在问"关于搜索"的知识，不是命令去搜索。
    #    必须在强指令之前 —— 「什么是网络搜索」本身就含强指令词。
    if _looks_interrogative(user_query):
        return False

    # ② 强指令：渠道与动作已连写在一起，意图无歧义
    if any(_normalize(s) in norm for s in _STRONG):
        return True

    # ③ 双信号：渠道 + 动作 都出现才算指令
    has_channel = any(_normalize(c) in norm for c in _CHANNEL)
    has_action = any(_normalize(a) in norm for a in _ACTION)
    return has_channel and has_action


def strip_web_directive(user_query: str) -> str:
    """从 query 里剥掉联网指令部分，返回"真正要查的内容"。

    ════════════════════════════════════════════════════════════════
    为什么必须剥离
    ════════════════════════════════════════════════════════════════
    用户实测输入：

        请你触发 网页搜索，进行"法国最低饮酒年龄"的资料搜索

    若把整句原样送去检索，"请你触发""网页搜索""进行""的资料搜索"
    这些**指令性废词**会一起参与向量编码与关键词匹配，把语义中心
    从"法国饮酒年龄"稀释掉，检索质量反而比直接问更差。

    做法保守：
      * 优先取引号内的内容 —— 用户用引号括起来时，那**就是**他要查的
        对象，这是最强、最无歧义的信号；
      * 否则删掉已知的指令词，保留剩余部分；
      * 若剥离后剩余内容过短（< 3 字），说明这句话几乎全是指令
        （如"联网搜一下"），此时**返回原句**交给上层处理 ——
        宁可带点噪声，也不能把 query 变成空串导致检索崩掉。
    """
    raw = (user_query or "").strip()
    if not raw:
        return raw

    # 引号内容优先：用户显式标注了检索对象
    for pat in (r"[“\"']([^”\"']{2,})[”\"']", r"「([^」]{2,})」", r"『([^』]{2,})』"):
        m = re.search(pat, raw)
        if m:
            return m.group(1).strip()

    # 逐个删除指令性词汇（长词优先，避免"搜索"先把"网页搜索"拆散）
    cleaned = raw
    for w in sorted(set(_STRONG + _ACTION + _CHANNEL), key=len, reverse=True):
        cleaned = re.sub(re.escape(w), " ", cleaned, flags=re.IGNORECASE)
    # 常见指令性虚词与残留标点
    for w in ("请你", "请帮我", "帮我", "请", "麻烦", "你能", "能否", "一下",
              "进行", "的资料", "资料", "关于", "有关", "我想", "我要",
              "重新", "再", "另外", "此外"):
        cleaned = cleaned.replace(w, " ")
    cleaned = re.sub(r"[\s，,。.、；;：:！!？?\"'“”‘’]+", " ", cleaned).strip()

    # 剥得太干净 → 说明整句都是指令，保留原句更安全
    return cleaned if len(cleaned) >= 3 else raw
