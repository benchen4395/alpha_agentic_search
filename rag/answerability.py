# rag/answerability.py
"""证据可答性（answerability）判据 —— 修复①。

════════════════════════════════════════════════════════════════════════
为什么需要这个模块：置信度回答了「错误的问题」
════════════════════════════════════════════════════════════════════════
`rag/calibration.py` 解决的是「跨层分数不可比」，它把 L2 的 BGE 余弦、
L4 的位次衰减、L5 的人工混合分统一映射到 P(relevant)。这一步是对的，
但它衡量的始终是**语义相似度**——「我召回的东西像不像这个话题」。

而 L4 兜底真正需要知道的是另一件事：
    「这些证据够不够回答用户的问题」

这两者在简单事实型问题上高度一致，但在**多跳 / 聚合 / 复合型问题**上
完全背离。实测三个 GAIA 风格的失败案例（用户真实提问）：

  ┌─────────────────────────────┬────────┬───────────────────────────┐
  │ 问题                        │ conf   │ 实际召回的证据             │
  ├─────────────────────────────┼────────┼───────────────────────────┤
  │ 小丑鱼 外来物种 USGS 邮编   │ 0.9800 │ 「小丑鱼是一种热带海水鱼」 │
  │ 茅盾文学奖 历届 获奖名单    │ 0.9286 │ 「茅盾文学奖1982年首届」   │
  │ 日本 今年 地震次数          │ 0.9839 │ 「2018年大阪地震…」        │
  └─────────────────────────────┴────────┴───────────────────────────┘

三条证据都**主题相关但完全不含答案**，可 conf 全部 ≥ 0.90，于是
`should_fallback_to_web(0.98)` = False → **L4 永远不会被触发** →
模型只能就着「小丑鱼是热带鱼」去回答「它在美国哪些邮编被发现」→ 拒答。

为什么 conf 会这么高？噪声-OR 只聚合 top-3（`AGG_TOP_N=3`），
实测饱和极快：

    L2 全部 8 条余弦 = 0.50  →  聚合 conf = 0.7308  →  不补 L4
    L2 全部 8 条余弦 = 0.55  →  聚合 conf = 0.8750  →  不补 L4
    L2 全部 8 条余弦 = 0.65  →  聚合 conf = 0.9876  →  不补 L4

也就是说，**只要有 3 条「沾边」的证据，置信度就会冲到 0.9+**。
这不是 calibration 的 bug——它忠实地报告了「这 3 条确实和话题相关」。
问题在于我们拿一个「相似度指标」去做「充分性决策」。

════════════════════════════════════════════════════════════════════════
解法：加一个与相似度**正交**的信号——关键词覆盖率
════════════════════════════════════════════════════════════════════════
核心洞察：如果 query 里的某个**实词**在所有召回证据里**一次都没出现**，
那这条证据几乎不可能回答涉及该词的问题。

  「邮政编码」「获奖名单」「次数」在证据里完全缺失
  → 无论语义多相似，答案都不可能在里面

实测同样四个 case 的覆盖率（按**单篇最佳**计算，见 `term_coverage`
里关于"为什么不能拼接全部证据"的说明），分离度非常干净：

    小丑鱼 外来物种 USGS 邮编   覆盖 0.40   缺失 [小丑鱼, 外来, 邮政编码]
    茅盾文学奖 历届 获奖名单    覆盖 0.50   缺失 [历届, 名单]
    日本 今年 地震次数          覆盖 0.50   缺失 [今年, 次数]
    美国有多少个州（正常 case）  覆盖 1.00   缺失 []

**失败案例 0.40~0.50，成功案例 1.00**——阈值放在 0.6 能干净切开。

为什么用词面覆盖而不是再上一个模型：
  ① **正交性**：它不看向量，所以不会和 conf 一起被"话题相似"骗到。
     两个信号从不同角度看同一批证据，才有互补价值。
  ② **零成本**：纯字符串匹配，实测 <1ms（BGE 编码要 60ms，
     cross-encoder 更贵）。放在 L4 判定这种**高频路径**上，
     不能再引入一次模型推理。
  ③ **可解释**：日志能直接打出"缺了哪些词"，排查时一眼看出
     是检索没召到还是问题本身超出了离线库覆盖范围。
  ④ **不可绕过**：LLM 判据（如 Self-RAG 的 ISREL token）需要额外
     一轮推理，且它自己也会幻觉；词面缺失是**客观事实**。

⚠️ 这个信号的**已知局限**（必须清楚，否则会误用）：
  * **同义词/跨语言不敏感**：query 说"邮编"、证据写"ZIP code"，
    会被判为缺失。这在本框架里是**可接受的保守方向**——
    误判会多补一次 L4（多花几秒、可能拿到更好证据），
    而漏判会直接导致拒答。**宁可多联网，不可少证据。**
  * 因此它只用来**触发补充检索**，绝不用来否决已有证据、
    也不参与最终 confidence 的计算（否则会污染来源面板的置信度显示）。
"""
from __future__ import annotations

import os
import re
from typing import Iterable, Optional

# ════════════════════════════════════════════════════════════════════════
#                              可调参数
# ════════════════════════════════════════════════════════════════════════
# 覆盖率低于此值 → 认为证据"答不上来"，应触发补充检索（L4）。
#
# 标定依据（见模块顶部实测表）：
#   失败案例落在 0.40 / 0.50 / 0.50，成功案例 1.00。
#   0.6 能把三个失败案例全部捞出，且不误伤正常问题。
#   不宜再往上调：那会让"证据其实够用、只是有个词没字面出现"的
#   正常问题也去联网，白付 8s 延迟。
MIN_TERM_COVERAGE: float = float(os.getenv("RAG_MIN_TERM_COVERAGE", "0.6"))

# 参与判定的最少实词数。
# 为什么需要下限：query 只有 1 个实词时，覆盖率只能是 0.0 或 1.0，
# 这种二值信号噪声太大（例如「量子纠缠」被切成一个词，证据里写的是
# 「量子」+「纠缠态」就会误判为 0）。实词太少时直接放弃判定，
# 退回只看 conf —— 保守，但不会制造新的误判。
MIN_TERMS_FOR_JUDGEMENT: int = int(os.getenv("RAG_MIN_TERMS_FOR_JUDGE", "3"))

# ════════════════════════════════════════════════════════════════════════
#                              停用词表
# ════════════════════════════════════════════════════════════════════════
# 这些词出现在 query 里但**不携带检索意图**，必须剔除，否则会稀释覆盖率。
#
# 特别注意包含了疑问词（多少/哪些/什么…）和量词（个/位/条…）：
# 它们描述的是"想要什么形式的答案"，而不是"要查什么主题"。
# 若不剔除，「美国有多少个州」的实词会变成
# {美国, 多少, 个, 州}，而证据里不会字面出现"多少"，
# 覆盖率被拉到 0.5 → 明明答对了却要去联网。
_STOPWORDS: frozenset[str] = frozenset("""
的 了 是 在 有 和 与 及 也 都 就 而 或 等 被 把 从 对 向 为 以 由 于
个 位 条 名 部 届 次 种 家 座 项
多少 哪些 哪个 哪里 什么 怎么 怎样 如何 为什么 为何 是否 能否
请 帮 我 你 他 她 它 我们 你们 他们 这 那 这些 那些 其 之
一共 总共 目前 现在 当前 已经 曾经 还有 以及 关于 根据 按照
information info list
""".split())

# 纯标点 / 纯符号的 token
_PUNCT_ONLY = re.compile(r"^[\W_]+$", re.UNICODE)


def _split_terms(text: str) -> list[str]:
    """把文本切成 token 列表。

    优先用 jieba（中文分词质量明显更好）；不可用时退回正则粗切，
    保证本模块在没装 jieba 的环境里依然能工作（只是精度略降）。
    """
    try:
        import jieba
        return list(jieba.lcut(text))
    except Exception:
        # 兜底：按「连续的中文字符 / 连续的字母数字」切分。
        # 中文没有空格，所以单个汉字也会被切出来——由下游的
        # len>1 过滤掉，避免单字噪声。
        return re.findall(r"[\u4e00-\u9fff]+|[A-Za-z0-9][A-Za-z0-9_\-]*", text)


def extract_key_terms(query: str) -> set[str]:
    """从 query 中抽取「必须在证据里出现」的实词集合。

    过滤规则（顺序无关，全部要满足）：
      * 长度 > 1 —— 单字（"州""鱼"）歧义太大，容易在无关证据里
        偶然命中，反而抬高覆盖率、掩盖真实缺失。
        例外见下方 ASCII 缩写处理。
      * 不在停用词表里
      * 不是纯标点

    ⚠️ ASCII 缩写单独放行：「USGS」「GDP」「AI」这类全大写缩写
    往往是问题的**核心检索锚点**，长度可能只有 2~3，绝不能被
    "长度 > 1" 之外的规则误伤。这里显式保留长度 ≥ 2 的纯字母数字 token。
    """
    out: set[str] = set()
    for tok in _split_terms(query or ""):
        w = tok.strip()
        if not w or _PUNCT_ONLY.match(w):
            continue
        if w.lower() in _STOPWORDS:
            continue
        # 纯 ASCII 字母/数字：放宽到长度 ≥ 2（保住 USGS / GDP / 2020 这类锚点）
        if re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_\-]*", w):
            if len(w) >= 2:
                out.add(w)
            continue
        if len(w) > 1:
            out.add(w)
    return out


def term_coverage(
    query: str,
    passages: Iterable,
    *,
    return_missing: bool = False,
):
    """计算 query 实词的**最佳单文档覆盖率** ∈ [0, 1]。

    Args:
        query:    原始（或改写后）的 query。
        passages: Passage-like 可迭代对象，只要求有 `.text`；
                  `.title` 存在时也一并计入（标题常含核心实体）。
        return_missing: True 时额外返回未命中的实词集合（用于日志）。

    Returns:
        `coverage` 或 `(coverage, missing_terms)`。

    ══════════════════════════════════════════════════════════════════
    ⚠️ 关键设计：按**单篇文档**算覆盖率，而不是把所有证据拼成一个 blob
    ══════════════════════════════════════════════════════════════════
    第一版实现是"拼接全部证据再做包含判断"，实测被一个真实案例打穿：

        query = "茅盾文学奖 历届 获奖名单"     实词 = {茅盾文学奖, 历届, 获奖, 名单}
        证据 = [
            L2「茅盾文学奖是中国作家协会主办的长篇小说奖…」  → 命中 {茅盾文学奖}
            L2「鲁迅文学奖…第五届开始评选范围中增加了获奖名单公示」→ 命中 {获奖, 名单}
        ]
        拼接后覆盖率 = 3/4 = 0.75   ← 判为"证据够用"，不补 L4 ❌

    可这两条证据讲的是**两个不同的奖**！「获奖名单」是从**鲁迅**文学奖
    那条完全无关的证据里命中的。拼接抹掉了"哪些词出现在同一篇里"这个
    至关重要的信息，让不相关的文档互相"凑"出高覆盖率。

    正确的语义是：**要有某一篇文档同时覆盖住问题的大部分实词**，
    才说明"答案可能在这一篇里"。所以改为逐篇计算、取最大值：

        单篇最佳覆盖率 = max(每篇文档覆盖的实词比例)

        L2-茅盾篇 → 1/4 = 0.25
        L2-鲁迅篇 → 2/4 = 0.50
        max      = 0.50  ← 低于 0.6，正确触发 L4 ✓

    这也更符合 RAG 的实际工作方式：LLM 是逐段读证据的，一个答案通常
    来自一到两段连续文本，而不是从五段互不相关的文字里拼凑。

    ══════════════════════════════════════════════════════════════════
    其它实现细节
    ══════════════════════════════════════════════════════════════════
      * 大小写归一化后做**子串包含**判断，而不是精确 token 相等。
        原因：中文分词在 query 与 passage 上的切分粒度经常不一致
        （query 切出"获奖名单"，passage 里是"获奖作品名单"），
        子串匹配对这类粒度差异更鲁棒。
      * query 实词不足 `MIN_TERMS_FOR_JUDGEMENT` 时返回 1.0
        （= "无异常"），让调用方退回只看 conf。返回 1.0 而不是 0.0
        很关键：0.0 会让所有短 query 都去联网。
      * `missing_terms` 报的是**最佳那一篇**还缺哪些词 —— 这才是
        "离最优证据还差什么"的准确描述。
    """
    terms = extract_key_terms(query)
    if len(terms) < MIN_TERMS_FOR_JUDGEMENT:
        # 样本太少，判据不可靠 → 明确表示"不构成负面证据"
        return (1.0, set()) if return_missing else 1.0

    # 逐篇计算覆盖率，取最好的那一篇（见上方设计说明）
    best_cov = 0.0
    best_missing: set[str] = set(terms)
    found_any_doc = False

    for p in passages or []:
        t = getattr(p, "text", "") or ""
        ti = getattr(p, "title", "") or ""
        doc = f"{ti} {t}".strip().lower()
        if not doc:
            continue
        found_any_doc = True
        missing = {w for w in terms if w.lower() not in doc}
        cov = 1.0 - len(missing) / len(terms)
        if cov > best_cov:
            best_cov = cov
            best_missing = missing

    if not found_any_doc:
        # 一条证据都没有 → 覆盖率 0（这是真正的"答不上来"）
        return (0.0, set(terms)) if return_missing else 0.0

    coverage = round(max(0.0, min(1.0, best_cov)), 4)
    return (coverage, best_missing) if return_missing else coverage


def is_evidence_insufficient(
    query: str,
    passages: Iterable,
    *,
    min_coverage: Optional[float] = None,
) -> tuple[bool, float, set[str]]:
    """判断「已召回的证据是否不足以回答该 query」。

    这是本模块对外的**主接口**，供 `LayeredRetriever` 在 L4 兜底
    判定处调用，与 `should_fallback_to_web(conf)` 形成 **OR 关系**：

        需要补 L4  ⟺  conf 偏低  OR  关键词覆盖率偏低

    为什么是 OR 而不是 AND：两个信号各自捕捉一类失败模式，
    互为补充而非互相制约。
      * conf 低、覆盖高 → 证据沾了词但语义弱（如同名异义）
      * conf 高、覆盖低 → **本次要修的正是这一类**（话题相关但不含答案）
    用 AND 会让任一信号失效就整体失效，等于白加。

    Returns:
        `(insufficient, coverage, missing_terms)`
        —— 后两项用于日志与可观测（`RetrievalResult` 会带上）。
    """
    thr = MIN_TERM_COVERAGE if min_coverage is None else min_coverage
    coverage, missing = term_coverage(query, passages, return_missing=True)
    return (coverage < thr), coverage, missing
