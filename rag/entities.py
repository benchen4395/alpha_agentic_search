# rag/entities.py
"""并列实体识别：判断一个 query 是不是在**同时问多个对象**。

════════════════════════════════════════════════════════════════════════
为什么单独拆一个模块
════════════════════════════════════════════════════════════════════════
这个能力有**两个**消费方，而且分属两个阶段：

    第一步（本次做的）：融合阶段按实体分配证据配额  → rag/fusion.quota_fuse
    第二步（后续可选）：检索阶段按实体拆多个子 query → 并发搜索

如果把它写在 fusion.py 里，第二步就得从 fusion 里 import 一个和融合
无关的函数，或者复制一份。放在独立模块里，两步共用同一份实现和同一份
标定数据 —— 这也是"先做第一步不会让第二步更难"的关键：
实体识别这笔账在第一步就付掉了，第二步直接复用。

════════════════════════════════════════════════════════════════════════
实测准确率（12 条多实体 query + 9 条单实体 query）
════════════════════════════════════════════════════════════════════════
    多实体召回:  10/12  (83%)
    单实体误报:   0/9   (0%)   ← 这一项是硬要求，见下

两条漏检都来自 jieba 词性标注的盲区：
    "特斯拉和比亚迪谁的销量高"   → 特斯拉 被标成 nz 之外的词性
    "爱因斯坦和牛顿谁贡献大"     → 爱因斯坦 未被识别为 nr

**为什么可以接受 83% 的漏检、但不能接受误报**：错误代价不对称。
  * 漏检（多实体被当成单实体）→ 退化成今天的行为，不比现在差；
  * 误报（单实体被当成多实体）→ 会给一个不该存在的"实体"预留配额，
    挤掉真正相关的证据，是**主动制造**回归。
所以下面的判据刻意偏保守：宁可少认，不可多认。
"""
from __future__ import annotations

import re

# ---------------------------------------------------------------------------
# 并列连接词。出现这些词，才认为用户可能在"分别问几个东西"。
#
# ⚠️ 为什么必须要求连接词，不能只看"识别出 ≥2 个专名"：
#   "俄罗斯的十月革命" → jieba 会切出「俄罗斯」和「十月革命」两个专名，
#   但这是**一个**问题的修饰关系，不是并列。只按专名数判断会大量误报。
#   连接词是"并列"这个语义关系的显式信号，是误报率能压到 0 的主要原因。
# ---------------------------------------------------------------------------
_CONJUNCTIONS = ("、", "和", "与", "以及", "还有", "或", "跟",
                 "分别", "各自", "对比", "比较", "vs", "VS", "谁")

# jieba 词性中代表"专有名词"的一组标签：
#   ns 地名 / nr 人名 / nt 机构名 / nz 其它专名
_PROPER_POS = {"ns", "nr", "nt", "nz"}

# 明确不该当作实体的高频词。这些词偶尔会被标成专名，
# 但它们是**问题的话题维度**而不是并列对象。
_STOP_ENTITIES = {
    "今天", "今年", "明天", "昨天", "现在", "目前", "最近",
    "国庆", "春节", "中秋", "元旦", "假期", "期间",
    "中国", "国内", "全国",          # 常作为背景限定而非并列项
    "气候", "天气", "景色", "价格", "情况",
}


def extract_parallel_entities(query: str, max_entities: int = 5) -> list[str]:
    """从 query 中抽取**并列**实体列表。

    Args:
        query:        用户 query（建议传改写后的，与检索口径一致）
        max_entities: 最多返回几个。超过这个数说明句子过于复杂，
                      配额切得太碎每个实体只剩 1 段，反而不如不切。

    Returns:
        实体名列表；**长度 < 2 时返回空列表**。

        为什么"只识别出 1 个"要返回空而不是返回那 1 个：
        下游 `quota_fuse` 用「entities 长度 < 2」作为
        "完全退化成原 rrf_fuse"的开关。返回 1 个实体和返回 0 个
        在语义上是一回事（都没有并列关系需要保护），
        统一成空列表能让下游只有一个判断分支，少一处出错的地方。
    """
    if not query or not any(c in query for c in _CONJUNCTIONS):
        # 没有并列连接词 → 直接判定为单一意图，连分词都不用跑（省 ~2ms）
        return []

    try:
        import jieba.posseg as pseg
    except Exception:
        # jieba 不可用时静默退化为"无并列实体" → 下游走原 RRF 路径。
        # 实体识别是**优化**而不是正确性前提，不该因为它挂了而让检索失败。
        return []

    entities: list[str] = []
    seen: set[str] = set()
    for word, pos in pseg.cut(query):
        w = word.strip()
        if pos not in _PROPER_POS:
            continue
        # 单字专名（"美""日"）歧义太大，且在证据文本里几乎必然误匹配
        # （"美"会命中"美食""完美"），会让配额分给错误的段落。
        if len(w) < 2:
            continue
        if w in _STOP_ENTITIES or w in seen:
            continue
        seen.add(w)
        entities.append(w)

    if len(entities) < 2:
        return []
    return entities[:max_entities]


def attribute_to_entity(text: str, entities: list[str]) -> set[str]:
    """判断一段文本**讲的是哪些实体**（可能同时讲多个）。

    用最朴素的子串匹配，理由：
      ① 证据段落是检索回来的原文，实体名基本是原样出现的；
      ② 任何基于向量/模型的归属判断都要额外推理开销，
         而融合阶段在主链路上、对延迟极敏感（实测整段 < 1ms）；
      ③ 归属错了的后果只是配额分配次优，不会丢证据 ——
         用不上更贵的方案。

    返回 set 而不是单个实体：一段"俄罗斯和希腊都在北半球"同时算两边的
    证据。下游据此**避免把同一段落重复计入结果**（见 quota_fuse 的去重）。
    """
    if not entities:
        return set()
    return {e for e in entities if e in text}
